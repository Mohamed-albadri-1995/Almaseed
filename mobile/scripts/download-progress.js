const fs = require('fs');
const path = require('path');

const appPath = path.join(__dirname, '..', 'App.js');
const source = fs.readFileSync(appPath, 'utf8');

const start = source.indexOf('function Downloads({ material }) {');
const end = source.indexOf('\nfunction Library', start);
if (start < 0 || end < 0) {
  throw new Error('Downloads function boundary not found');
}

const replacement = [
  'function Downloads({ material }) {',
  '  const [busy, setBusy] = useState(false);',
  '  const [progress, setProgress] = useState(0);',
  '  const [downloaded, setDownloaded] = useState(0);',
  '  const [total, setTotal] = useState(0);',
  '',
  '  const resetProgress = () => {',
  '    setProgress(0);',
  '    setDownloaded(0);',
  '    setTotal(0);',
  '  };',
  '',
  '  const ensureLocal = async () => {',
  '    const sourceUrl = material.fileKind === \'DOCUMENT\'',
  '      ? \'https://almaseeed.com/api/materials/\' + material.id + \'/download\'',
  '      : material.fileUrl;',
  '    if (!sourceUrl) throw new Error(\'لا يوجد ملف للتنزيل\');',
  '',
  '    const ext = material.fileKind === \'DOCUMENT\' ? \'pdf\' : ((material.fileType || \'bin\').toLowerCase().replace(/[^a-z0-9]/g, \'\') || \'bin\');',
  '    const safeTitle = (material.title || \'مادة\').replace(/[\\/:*?"<>|]/g, \'-\').trim() || \'مادة\';',
  '    const fileName = safeTitle + \'.\' + ext;',
  '    const dir = FileSystem.documentDirectory + \'almaseed-downloads/\';',
  '    await FileSystem.makeDirectoryAsync(dir, { intermediates: true }).catch(() => {});',
  '    const dest = dir + fileName;',
  '',
  '    const info = await FileSystem.getInfoAsync(dest);',
  '    if (info.exists) {',
  '      setDownloaded(info.size || 0);',
  '      setTotal(info.size || 0);',
  '      setProgress(1);',
  '      return dest;',
  '    }',
  '',
  '    const task = FileSystem.createDownloadResumable(',
  '      sourceUrl,',
  '      dest,',
  '      {},',
  '      (downloadProgress) => {',
  '        const written = downloadProgress.totalBytesWritten || 0;',
  '        const expected = downloadProgress.totalBytesExpectedToWrite || 0;',
  '        setDownloaded(written);',
  '        setTotal(expected);',
  '        if (expected > 0) setProgress(written / expected);',
  '      }',
  '    );',
  '',
  '    const result = await task.downloadAsync();',
  '    if (!result || !result.uri) throw new Error(\'فشل تنزيل الملف\');',
  '    setProgress(1);',
  '    return result.uri;',
  '  };',
  '',
  '  const saveDownload = async () => {',
  '    if (busy) return;',
  '    setBusy(true);',
  '    resetProgress();',
  '    try {',
  '      const uri = await ensureLocal();',
  '      await addDownload({',
  '        id: material.id, title: material.title, subtitle: material.subtitle || null,',
  '        person: material.performer || material.speaker || material.host || material.author || null,',
  '        fileKind: material.fileKind, localPath: uri, bodyText: material.bodyText || null,',
  '        savedAt: Date.now(),',
  '      });',
  '      Alert.alert(\'تم التنزيل\', \'تم حفظ المادة داخل التطبيق.\');',
  '    } catch (e) {',
  '      Alert.alert(\'تعذّر التنزيل\', String(e.message || e));',
  '    } finally {',
  '      setBusy(false);',
  '    }',
  '  };',
  '',
  '  const saveToDevice = async () => {',
  '    if (busy) return;',
  '    setBusy(true);',
  '    resetProgress();',
  '    try {',
  '      const uri = await ensureLocal();',
  '      if (material.fileKind === \'AUDIO\' || material.fileKind === \'VIDEO\' || material.fileKind === \'IMAGE\') {',
  '        await MediaLibrary.saveToLibraryAsync(uri);',
  '        Alert.alert(\'تم التنزيل\', \'تم حفظ الملف على الجهاز.\');',
  '      } else if (await Sharing.isAvailableAsync()) {',
  '        await Sharing.shareAsync(uri);',
  '      } else {',
  '        Alert.alert(\'تم التنزيل\', \'تم حفظ الملف داخل التطبيق.\');',
  '      }',
  '    } catch (e) {',
  '      Alert.alert(\'تعذّر الحفظ\', String(e.message || e));',
  '    } finally {',
  '      setBusy(false);',
  '    }',
  '  };',
  '',
  '  const pct = Math.max(0, Math.min(100, Math.round(progress * 100)));',
  '  const mb = (n) => (n / 1048576).toFixed(1);',
  '',
  '  return <View style={{ marginTop: 14 }}>',
  '    {busy && <View style={{ marginBottom: 10 }}>',
  '      <View style={{ height: 6, borderRadius: 3, backgroundColor: C.line, overflow: \'hidden\' }}>',
  '        <View style={{ width: pct + \'%\', height: 6, backgroundColor: C.brand }} />',
  '      </View>',
  '      <View style={{ flexDirection: \'row\', justifyContent: \'space-between\', marginTop: 5 }}>',
  '        <Text style={{ color: C.muted, fontSize: 12 }}>{total > 0 ? mb(downloaded) + \' / \' + mb(total) + \' MB\' : \'جارٍ تجهيز التنزيل\'}</Text>',
  '        <Text style={{ color: C.brand, fontSize: 12, fontWeight: \'800\' }}>{pct}%</Text>',
  '      </View>',
  '    </View>}',
  '    <View style={{ flexDirection: \'row\', gap: 8 }}>',
  '      <TouchableOpacity style={styles.downloadBtn} onPress={saveDownload} disabled={busy}>',
  '        <Text style={styles.downloadBtnTxt}>{busy ? \'جاري التنزيل \' + pct + \'%\' : \'تنزيل\'}</Text>',
  '      </TouchableOpacity>',
  '      <TouchableOpacity style={styles.downloadBtnAlt} onPress={saveToDevice} disabled={busy}>',
  '        <Text style={styles.downloadBtnAltTxt}>{busy ? \'\' : \'حفظ على الجهاز\'}</Text>',
  '      </TouchableOpacity>',
  '    </View>',
  '  </View>;',
  '}',
].join('\n');

const updated = source.slice(0, start) + replacement + source.slice(end);
fs.writeFileSync(appPath, updated, 'utf8');
console.log('Download progress UI prepared.');
